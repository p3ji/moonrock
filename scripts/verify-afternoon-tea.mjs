import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync, readdirSync } from 'node:fs';
import worker from '../worker.mjs';
const db = new DatabaseSync(':memory:');
const migrations = new URL('../migrations/', import.meta.url);
const migration = readFileSync(new URL('0010_afternoon_tea.sql', migrations), 'utf8');
for (const file of readdirSync(migrations).filter(file => file.endsWith('.sql') && file < '0010').sort()) db.exec(readFileSync(new URL(file, migrations), 'utf8'));
db.exec("INSERT INTO orders(id,request_id,round_id,guest_name,items) VALUES('fixture','fixture-existing','first-gathering','Fixture','[]')");
const snapshot = table => db.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all();
const rounds = snapshot('rounds'), orders = snapshot('orders'), menus = snapshot('menus');
db.exec(migration);
assert.deepEqual(snapshot('rounds'), rounds);
assert.deepEqual(snapshot('orders'), orders);
assert.deepEqual(snapshot('menus').filter(menu => menu.id !== 'moonrock-afternoon-tea'), menus);
const menu = db.prepare("SELECT * FROM menus WHERE id='moonrock-afternoon-tea'").get();
assert.equal(menu.title, 'Afternoon Tea');
const sections = JSON.parse(menu.sections), items = sections.flatMap(section => section.items);
assert.deepEqual(items.map(item => item.en).sort(), ['Charcuterie board','Melon bowl','Jalapeño poppers','Milk fudge','Profiteroles','Shrimp dumplings (hot)','Shrimp rings (cold)','Asian snacks (assorted)','Tea','Coffee (18+)'].sort());
const original = JSON.parse(readFileSync(new URL('../src/catalog.json', import.meta.url)));
assert.deepEqual(items.filter(item => item.options.length), original.sections.flatMap(section => section.items).filter(item => ['drinks-6','drinks-7'].includes(item.id)));
assert.equal(new Set(items.map(item => item.id)).size, items.length);
const DB = { prepare(sql) { return { args: [], bind(...args) { this.args = args; return this; }, async first() { return db.prepare(sql).get(...this.args) || null; }, async all() { return { results: db.prepare(sql).all(...this.args) }; }, async run() { return { meta: { changes: db.prepare(sql).run(...this.args).changes } }; } }; }, async batch(statements) { db.exec('BEGIN'); try { const results = []; for (const statement of statements) results.push(await statement.run()); db.exec('COMMIT'); return results; } catch (error) { db.exec('ROLLBACK'); throw error; } } };
const origin = 'https://cafe.example';
const call = (path, data) => worker.fetch(new Request(origin + path, data ? { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify(data) } : {}), { DB, HOST_OPEN: 'true' });
const state = await (await call('/api/back')).json();
assert(state.menus.some(menu => menu.id === 'moonrock-afternoon-tea'));
const started = await call('/api/back/start', { menuId: menu.id, title: 'Fixture tea', expectedRoundId: 'first-gathering' });
assert.equal(started.status, 201);
const active = await (await call('/api/menu')).json();
assert.equal(active.menuTitle, 'Afternoon Tea');
const feed = await (await call('/api/iot/orders?feed=2')).json();
const submission = { name: 'Fixture', roundId: active.roundId, requestId: 'fixture-afternoon-tea-0001', items: items.map(item => ({ itemId: item.id, optionId: item.options[0]?.id || '', quantity: 1 })) };
assert.equal((await call('/api/orders', submission)).status, 201);
assert.equal((await call('/api/orders', submission)).status, 200);
const events = await (await call('/api/iot/orders?feed=2&after=' + encodeURIComponent(feed.cursor))).json();
assert.equal(events.events.length, 1);
assert.equal(events.events[0].totalItems, 10);
db.prepare("UPDATE menus SET title='Host edited title' WHERE id=?").run(menu.id);
db.exec(migration);
assert.equal(db.prepare('SELECT title FROM menus WHERE id=?').get(menu.id).title, 'Host edited title');
db.close();
